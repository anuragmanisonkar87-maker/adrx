"""Checks for the mandatory disclosures in clause 3.2 Explanations III/IV and the AI source mark (7.2)."""

from __future__ import annotations

import re
from dataclasses import dataclass

# Channels that count as "electronic media" for Explanations III/IV.
ELECTRONIC_CHANNELS = {"social", "youtube", "website", "whatsapp", "tv_radio"}
DISCLOSING_PUBLISHERS = {"rmp", "hospital", "agency"}

DOCTOR_NAME = re.compile(r"\b(?:Dr|DR|dr|Doctor|DOCTOR)\.?\s+[A-Z][A-Za-z.'-]+|डॉ[.०]?\s*\S+|डा[.०]\s*\S+|डॉक्टर\s+\S+")
QUALIFICATION = re.compile(
    r"(?<![A-Za-z])(?:"
    r"M\.?\s?B\.?\s?B\.?\s?S|B\.?\s?D\.?\s?S|M\.?\s?D\.?\s?S|B\.?\s?A\.?\s?M\.?\s?S|B\.?\s?H\.?\s?M\.?\s?S|"
    r"B\.?\s?U\.?\s?M\.?\s?S|B\.?\s?N\.?\s?Y\.?\s?S|D\.?\s?N\.?\s?B|DrNB|M\.?\s?Ch|"
    r"M\.?\s?D|M\.?\s?S|D\.?\s?M(?!\s*(?:us|me|now|for)\b)|F\.?\s?R\.?\s?C\.?\s?S|M\.?\s?R\.?\s?C\.?\s?P|"
    r"M\.?\s?R\.?\s?C\.?\s?O\.?\s?G|F\.?\s?C\.?\s?P\.?\s?S|D\.?\s?G\.?\s?O|D\.?\s?C\.?\s?H|D\.?\s?P\.?\s?M|"
    r"D\.?\s?L\.?\s?O|D\.?\s?O\.?\s?M\.?\s?S|D\.?\s?V\.?\s?D|F\.?\s?N\.?\s?B|M\.?\s?P\.?\s?T|B\.?\s?P\.?\s?T|"
    r"Ph\.?\s?D|M\.?\s?P\.?\s?H|F\.?\s?A\.?\s?C\.?\s?S|F\.?\s?I\.?\s?C\.?\s?S|DDVL|FICOG|FMAS"
    r")(?![A-Za-z])"
    r"|एमबीबीएस|एम\.?\s?डी|एम\.?\s?एस|बीएएमएस|बीएचएमएस|बीडीएस|एमडीएस"
)
REGISTRATION = re.compile(
    r"(?:\breg(?:istration|istered|d|n)?\.?\s*(?:no|num|number|id)?\.?\s*[:#-]?\s*"
    r"|\b(?:NMR|SMR)\s*(?:id|no|number)?\.?\s*[:#-]?\s*"
    r"|\b(?:[A-Z]{1,4}MC|MCI|NMC|DMCR?)\s*(?:reg(?:n|d|istration)?\.?\s*)?(?:no\.?|number)?\s*[:#-]?\s*)"
    r"[A-Z]{0,5}[/-]?\s?\d[\d/-]{2,}"
    r"|(?:पंजीकरण|रजिस्ट्रेशन)\s*(?:संख्या|सं\.?|नं\.?|नंबर)?\s*[:-]?\s*\d{3,}",
    re.IGNORECASE,
)
AI_LABEL = re.compile(
    r"\b(?:ai[- ](?:generated|assisted|created|made)"
    r"|(?:generated|created|made)\s+(?:by|using|with)\s+(?:an?\s+)?(?:ai|artificial\s+intelligence)"
    r"|source\s*:\s*ai)\b|#aigenerated"
    r"|एआई\s+(?:द्वारा|से)\s+(?:बनाया|बनाई|निर्मित|तैयार|जनरेट)",
    re.IGNORECASE,
)

ITEM_LABELS = {
    "doctor_name": "Doctor's name",
    "qualifications": "Recognised qualifications",
    "registration_number": "Registration status and SMC/NMR registration number",
    "ai_source_label": '"AI-generated" source mark',
    "other": "Other disclosure",
}


@dataclass
class DisclosureCheck:
    required: bool
    doctor_name: str | None
    qualifications: str | None
    registration_number: str | None
    ai_label: str | None

    def missing(self, ai_used: str) -> list[dict]:
        items: list[dict] = []
        if self.required:
            if not self.doctor_name:
                items.append(_item("doctor_name", "Name of the doctor (RMP) is not shown."))
            if not self.qualifications:
                items.append(_item("qualifications", "Qualifications (e.g. MBBS, MD) are not shown."))
            if not self.registration_number:
                items.append(
                    _item(
                        "registration_number",
                        "Registration status and State Medical Council / NMR registration number "
                        "(e.g. 'Reg. No. MMC 2012/03/1234') are not shown.",
                    )
                )
        if ai_used == "yes" and not self.ai_label:
            items.append(
                _item(
                    "ai_source_label",
                    "AI-generated content must carry a source mark stating that it was generated by AI.",
                    clause="7.2",
                )
            )
        return items

    def as_hint(self) -> str:
        def show(value: str | None) -> str:
            return f'found ("{value}")' if value else "not found"

        return (
            f"doctor's name: {show(self.doctor_name)}; qualifications: {show(self.qualifications)}; "
            f"registration no.: {show(self.registration_number)}; AI label: {show(self.ai_label)}"
        )


def _item(item: str, detail: str, clause: str = "3.2 Expl. III/IV") -> dict:
    return {"item": item, "label": ITEM_LABELS[item], "detail": detail, "clause": clause}


def disclosure_required(publisher: str, channel: str) -> bool:
    return publisher in DISCLOSING_PUBLISHERS and channel in ELECTRONIC_CHANNELS


def check(text: str, publisher: str, channel: str) -> DisclosureCheck:
    def first(pattern: re.Pattern) -> str | None:
        match = pattern.search(text)
        return match.group(0).strip()[:60] if match else None

    return DisclosureCheck(
        required=disclosure_required(publisher, channel),
        doctor_name=first(DOCTOR_NAME),
        qualifications=first(QUALIFICATION),
        registration_number=first(REGISTRATION),
        ai_label=first(AI_LABEL),
    )
